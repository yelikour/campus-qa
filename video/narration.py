def tts(seg_id: str, text: str) -> Path:
    aiff = AUDIO / f"seg{seg_id}.aiff"
    m4a = AUDIO / f"seg{seg_id}.m4a"
    subprocess.run(["say", "-v", "Tingting", text, "-o", str(aiff)], check=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(aiff),
                    "-c:a", "aac", "-b:a", "128k", str(m4a)], check=True)
    aiff.unlink()
    return m4a

def dur(path: Path) -> float:
    return float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                 "-of", "csv=p=0", str(path)], capture_output=True, text=True).stdout.strip())

if __name__ == "__main__":
    total = 0.0
    for seg_id, _, text in SEGMENTS:
        out = AUDIO / f"seg{seg_id}.m4a"
        if not out.exists() or "--force" in sys.argv:
            out = tts(seg_id, text)
        d = dur(out)
        total += d
        print(f"seg{seg_id}: {d:.1f}s")
    print(f"18 narration segments total: {total:.1f}s (+ demo 60.1s + gaps)")
